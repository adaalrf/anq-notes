import {
  lstat,
  readFile,
  readdir,
  mkdir,
  mkdtemp,
  writeFile,
  rename,
  rm,
  open,
} from 'node:fs/promises';
import { join, resolve, dirname } from 'node:path';
import { randomUUID } from 'node:crypto';
import { validateConfig } from './config.js';
import { readContent, tagSlug, type Document } from './content.js';
import { layout, escape } from './render.js';
import { contentPage } from './pages/page.js';
import { postPage } from './pages/post.js';
import { listingPage } from './pages/listing.js';
import { topicsPage } from './pages/topics.js';
import { notFoundPage } from './pages/not-found.js';
import { checkLinks } from './links.js';
const marker = '.anq-ssg-output';
// Stable ownership format: display-name changes must not orphan existing output.
const markerText = 'Generated by Anq Blog SSG v1. Edit content/, not public/.\n';
async function exists(path: string) {
  try {
    await lstat(path);
    return true;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return false;
    throw error;
  }
}
async function regularFile(path: string) {
  const stat = await lstat(path);
  if (!stat.isFile() || stat.isSymbolicLink())
    throw new Error(`${path}: expected a regular file, not a symlink.`);
  return readFile(path);
}
async function assets(root: string, relative: string, files: Map<string, string | Buffer>) {
  const path = join(root, relative),
    stat = await lstat(path);
  if (stat.isSymbolicLink() || !stat.isDirectory())
    throw new Error(`${path}: expected a real directory.`);
  for (const entry of (await readdir(path, { withFileTypes: true })).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    if (entry.name.startsWith('.'))
      throw new Error(`${relative}/${entry.name}: hidden asset files are not copied.`);
    const source = join(relative, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`${source}: asset symlinks are not supported.`);
    if (entry.isDirectory()) await assets(root, source, files);
    else if (entry.isFile())
      files.set(source.split('\\').join('/'), await regularFile(join(root, source)));
    else throw new Error(`${source}: unsupported asset type.`);
  }
}
const outputPath = (url: string) => (url === '/' ? 'index.html' : url.slice(1) + 'index.html');
export async function build(root: string, rawConfig: unknown) {
  root = resolve(root);
  const config = validateConfig(rawConfig),
    output = join(root, 'public');
  // A stale lock is deliberately not removed automatically after a crashed build.
  const lockPath = join(root, '.anq-build.lock');
  let lock;
  try {
    lock = await open(lockPath, 'wx');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'EEXIST')
      throw new Error(
        'Another build holds .anq-build.lock. If it crashed, confirm it stopped before removing the lock.',
      );
    throw error;
  }
  let stage: string | undefined, previous: string | undefined;
  try {
    for (const directory of ['content', 'styles', 'templates']) {
      const stat = await lstat(join(root, directory));
      if (!stat.isDirectory() || stat.isSymbolicLink())
        throw new Error(`${directory}: expected a real source directory.`);
    }
    if (await exists(output)) {
      const stat = await lstat(output);
      if (
        !stat.isDirectory() ||
        stat.isSymbolicLink() ||
        !(await exists(join(output, marker))) ||
        (await regularFile(join(output, marker))).toString() !== markerText
      )
        throw new Error(
          'public/ is not a recognized generated directory. It was preserved; move it aside explicitly.',
        );
    }
    const [pages, posts, template, tokens, css] = await Promise.all([
      readContent(join(root, 'content/pages'), 'page'),
      readContent(join(root, 'content/posts'), 'post'),
      regularFile(join(root, 'templates/layout.html')).then((b) => b.toString()),
      regularFile(join(root, 'styles/tokens.css')),
      regularFile(join(root, 'styles/site.css')),
    ]);
    if (!pages.some((page) => page.url === '/'))
      throw new Error('Provide a published content/pages/index.md (or .html) homepage.');
    const files = new Map<string, string | Buffer>();
    const add = (path: string, body: string | Buffer) => {
      if (files.has(path))
        throw new Error(`Output collision: ${path}. Check page/post slugs and reserved routes.`);
      files.set(path, body);
    };
    const html = (title: string, description: string, url: string, body: string, noindex = false) =>
      add(outputPath(url), layout(template, config, title, description, url, body, noindex));
    add('styles/tokens.css', tokens);
    add('styles/site.css', css);
    await assets(root, 'assets', files);
    for (const page of pages) {
      if (['blog', 'tags', '404', 'assets', 'styles'].includes(page.slug))
        throw new Error(`${page.source}: reserved page slug "${page.slug}".`);
      html(page.title, page.description, page.url, contentPage(page, config.title));
    }
    for (const [index, post] of posts.entries()) {
      html(
        post.title,
        post.description,
        post.url,
        postPage(post, posts[index - 1], posts[index + 1]),
      );
    }
    const listing = (title: string, description: string, items: Document[], base: string) => {
      const count = Math.max(1, Math.ceil(items.length / config.postsPerPage));
      const url = (page: number) => (page === 1 ? base : `${base}page/${page}/`);
      for (let page = 1; page <= count; page++)
        html(
          page === 1 ? title : `${title} — Page ${page}`,
          description,
          url(page),
          listingPage(
            title,
            description,
            items.slice((page - 1) * config.postsPerPage, page * config.postsPerPage),
            page,
            count,
            url,
            base.startsWith('/tags/'),
          ),
        );
    };
    listing('Writing', config.description, posts, '/blog/');
    const tags = new Map<string, { label: string; posts: Document[] }>();
    for (const post of posts)
      for (const tag of post.tags) {
        const slug = tagSlug(tag),
          existing = tags.get(slug);
        if (existing && existing.label !== tag)
          throw new Error(
            `Tags "${existing.label}" and "${tag}" map to the same URL. Use one consistent label.`,
          );
        if (existing) existing.posts.push(post);
        else tags.set(slug, { label: tag, posts: [post] });
      }
    const tagEntries = [...tags.entries()].sort(([a], [b]) => a.localeCompare(b));
    html('Topics', 'Browse notes by subject.', '/tags/', topicsPage(tagEntries));
    for (const [slug, tag] of tagEntries)
      listing(tag.label, `Notes filed under ${tag.label}.`, tag.posts, `/tags/${slug}/`);
    add(
      '404.html',
      layout(
        template,
        config,
        'Page not found',
        'This page is not here.',
        '/404.html',
        notFoundPage(),
        true,
      ),
    );
    const canonical = (url: string) => escape(config.url + url);
    const latest = posts[0]?.date
      ? new Date(posts[0].date + 'T00:00:00Z').toUTCString()
      : new Date('2000-01-01T00:00:00Z').toUTCString();
    add(
      'rss.xml',
      `<?xml version="1.0" encoding="UTF-8"?><rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom"><channel><title>${escape(config.title)}</title><link>${canonical('/')}</link><description>${escape(config.description)}</description><language>${escape(config.language)}</language><lastBuildDate>${latest}</lastBuildDate><atom:link href="${canonical('/rss.xml')}" rel="self" type="application/rss+xml"/>${posts
        .slice(0, 20)
        .map(
          (post) =>
            `<item><title>${escape(post.title)}</title><link>${canonical(post.url)}</link><guid isPermaLink="true">${canonical(post.url)}</guid><pubDate>${new Date(post.date + 'T00:00:00Z').toUTCString()}</pubDate><description>${escape(post.description)}</description>${post.tags.map((tag) => `<category>${escape(tag)}</category>`).join('')}</item>`,
        )
        .join('')}</channel></rss>`,
    );
    const routes = [...files.keys()]
      .filter((file) => file.endsWith('index.html'))
      .sort()
      .map((file) => (file === 'index.html' ? '/' : '/' + file.slice(0, -10)));
    add(
      'sitemap.xml',
      `<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">${routes.map((url) => `<url><loc>${canonical(url)}</loc></url>`).join('')}</urlset>`,
    );
    add(
      'robots.txt',
      `User-agent: *\n${config.indexable ? 'Allow: /' : 'Disallow: /'}\nSitemap: ${config.url}/sitemap.xml\n`,
    );
    add(marker, markerText);
    checkLinks(files, config.url);
    stage = await mkdtemp(join(root, '.anq-build-'));
    for (const [path, body] of files) {
      const destination = join(stage, path);
      await mkdir(dirname(destination), { recursive: true });
      await writeFile(destination, body);
    }
    if (await exists(output)) {
      previous = join(root, `.anq-previous-${randomUUID()}`);
      await rename(output, previous);
    }
    try {
      await rename(stage, output);
      stage = undefined;
    } catch (error) {
      if (previous) {
        await rename(previous, output);
        previous = undefined;
      }
      throw error;
    }
    if (previous) {
      await rm(previous, { recursive: true });
      previous = undefined;
    }
    return { pages: pages.length, posts: posts.length, tags: tags.size, files: files.size };
  } finally {
    if (stage) await rm(stage, { recursive: true, force: true });
    await lock.close();
    await rm(lockPath, { force: true });
  }
}
